export function sitesInCountry(country) {
  return CATERPILLAR_GLOBAL_NETWORK.filter((s) => s.country === country);
}

export function statesInCountry(country) {
  const states = new Map();
  for (const site of sitesInCountry(country)) {
    if (!site.state) continue;
    if (!states.has(site.state)) {
      states.set(site.state, {
        name: site.state,
        country,
        lat: site.coordinates.lat,
        lng: site.coordinates.lng,
        siteCount: 1,
      });
    } else {
      const s = states.get(site.state);
      s.siteCount += 1;
      s.lat = (s.lat + site.coordinates.lat) / 2;
      s.lng = (s.lng + site.coordinates.lng) / 2;
    }
  }
  return [...states.values()];
}
